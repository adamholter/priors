import assert from "node:assert/strict";
import { chromium } from "playwright";
import { createRequire } from "node:module";
import "tsx/cjs";
const require = createRequire(import.meta.url);
const { computeIndex, selectVariants } = require("../src/engine/index.ts");
const { decodeIndex } = require("../src/lib/url.ts");

const base = process.env.TEST_URL ?? "http://127.0.0.1:48740";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
const mix = "General%20frontier|aa-gdpval-aa:15,aa-terminalbench-v2-1:15,deepswe-1.1:15,terminalbench-4:10,arc-agi-3:10,simplebench:10";
try {
  const { snapshot } = await (await page.request.get(`${base}/api/snapshot`)).json();
  const config = decodeIndex(mix, "g");
  const expected = computeIndex(snapshot, config);
  const modelCount = selectVariants(expected.ranked, "best").length;
  const strictCount = selectVariants(computeIndex(snapshot, { ...config, effortMatching: "strict" }).ranked, "best").length;
  assert(modelCount > strictCount, "calibrated evidence should broaden this benchmark mix");
  await page.goto(`${base}/?${new URLSearchParams({ i: mix })}`, { waitUntil: "networkidle" });
  await page.getByText(`6 benchmarks · ${modelCount} models`, { exact: true }).waitFor();
  assert.equal(await page.locator("[data-k]").count(), 8);
  assert(!(await page.locator("body").innerText()).includes("≈"));
  assert.equal(await page.getByRole("combobox", { name: "Effort estimates" }).count(), 0);
  assert.equal(await page.getByRole("checkbox", { name: /required$/ }).count(), 6);
  await page.getByLabel("Ranking settings", { exact: true }).click();
  assert.equal(await page.getByRole("combobox", { name: "Ranking reasoning efforts" }).inputValue(), "best");
  await page.getByRole("combobox", { name: "Ranking reasoning efforts" }).selectOption("all");
  assert(await page.locator("[data-k]").count() > 8);
  await page.getByLabel("Pareto settings", { exact: true }).click();
  assert.equal(await page.getByRole("combobox", { name: "Pareto reasoning efforts" }).inputValue(), "all");
  await page.getByRole("combobox", { name: "Pareto reasoning efforts" }).selectOption("best");
  assert(await page.locator("[data-k]").count() > 8, "Pareto mode must not change bar rows");
  await page.waitForTimeout(300);
  await page.reload({ waitUntil: "networkidle" });
  assert(await page.locator("[data-k]").count() > 8);
  await page.getByLabel("Ranking settings", { exact: true }).click();
  await page.getByRole("combobox", { name: "Ranking reasoning efforts" }).selectOption("best");
  await page.getByLabel("Pareto settings", { exact: true }).click();
  assert.equal(await page.getByRole("combobox", { name: "Pareto reasoning efforts" }).inputValue(), "best");
  await page.getByRole("combobox", { name: "Pareto reasoning efforts" }).selectOption("all");
  await page.getByLabel("Pareto settings", { exact: true }).click();
  await page.getByRole("button", { name: "Calculation settings", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Calculation settings" });
  await dialog.getByRole("combobox", { name: "Inspect model calculation" }).selectOption("claude-opus-5@high");
  await dialog.getByText(/high.*max|comparisons/).first().waitFor();
  await dialog.screenshot({ path: "/tmp/priors-calculation-settings.png" });
  await dialog.getByRole("combobox", { name: "Effort estimates" }).selectOption("strict");
  await dialog.getByRole("button", { name: "Close calculation settings" }).click();
  assert.equal(await page.locator("[data-k]").count(), 2);
  await page.getByRole("button", { name: "Calculation settings", exact: true }).click();
  await dialog.getByRole("combobox", { name: "Effort estimates" }).selectOption("calibrated");
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("[data-k]").count(), 8);
  const required = page.getByRole("checkbox", { name: "SimpleBench required", exact: true });
  await required.uncheck();
  const strictness = page.getByRole("slider", { name: "Strictness", exact: true });
  const setStrictness = (value) => strictness.evaluate((el, value) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set.call(el, value); el.dispatchEvent(new Event("input", { bubbles: true })); }, value);
  await setStrictness("90");
  assert.equal(await required.isChecked(), false, "manual optional overrides strictness");
  await setStrictness("0");
  await required.check();
  assert.equal(await required.isChecked(), true, "manual required overrides flexible policy");
  await setStrictness("50");
  await page.waitForTimeout(300);
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await required.isChecked(), true);
  await page.screenshot({ path: "/tmp/priors-simplified-desktop.png", fullPage: true });
  const share = await page.request.get(`${base}/og${new URL(page.url()).search}`);
  assert.equal(share.status(), 200);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: "/tmp/priors-simplified-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Calculation settings", exact: true }).click();
  assert(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), "advanced settings should fit mobile");
  await dialog.screenshot({ path: "/tmp/priors-calculation-settings-mobile.png" });
  assert.deepEqual(errors, []);
  console.log("Independent chart defaults, calibration settings, required overrides, strictness, URL persistence, share card and responsive UI passed.");
} finally { await browser.close(); }
