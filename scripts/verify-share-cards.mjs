import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const out = '/tmp/priors-share-cards';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });await page.addInitScript(()=>localStorage.setItem('priors:intro-seen','1'));
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => { Object.defineProperty(navigator, 'clipboard', { value: { writeText: async value => { window.__copied = value; } } }); });
  await page.goto('http://localhost:48740', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Card', exact: true }).click();
  const modal = page.getByRole('dialog', { name: 'Share card', exact: true });
  await modal.waitFor();
  const designs = modal.getByRole('button', { name: /^Design \d/ });
  assert.equal(await designs.count(), 13);
  const images = [];
  for (let i = 0; i < 10; i++) {
    await designs.nth(i).click();
    const preview = modal.getByRole('img', { name: /share card for/ });
    await preview.evaluate(img => img.complete && img.naturalWidth ? null : new Promise((resolve, reject) => { img.addEventListener('load', resolve, {once:true}); img.addEventListener('error', reject, {once:true}); }));
    assert.equal(await preview.evaluate(img => img.naturalWidth), 1200);
    const src = await preview.getAttribute('src');
    const response = await page.request.get(new URL(src, page.url()).href); assert(response.ok());
    const bytes = await response.body(); await writeFile(`${out}/design-${i+1}.png`, bytes);
    images.push({ name: await designs.nth(i).getAttribute('aria-label'), src });
  }
  await modal.getByRole('button', { name: 'Copy link', exact: true }).click();
  const copied = await page.evaluate(() => window.__copied); assert(new URL(copied).searchParams.get('design'));
  const intent = new URL(await modal.getByRole('link', { name: /Share on X/ }).getAttribute('href'));
  assert.equal(intent.hostname, 'twitter.com'); assert.equal(intent.searchParams.has('url'), false);
  const downloadPromise = page.waitForEvent('download');
  await modal.getByRole('link', { name: 'Download', exact: true }).click();
  const download = await downloadPromise; assert.match(download.suggestedFilename(), /^priors-.+\.png$/);
  assert.equal(page.context().pages().length, 1);
  await designs.nth(0).click();
  await modal.locator("[aria-busy=false]").waitFor();
  await page.screenshot({ path: `${out}/modal-desktop.png` });
  await page.keyboard.press('Escape'); assert(!await modal.isVisible());
  assert(await page.getByRole('button', { name: 'Card', exact: true }).evaluate(el => el === document.activeElement));
  await page.getByRole('button', { name: 'Card', exact: true }).click(); await page.mouse.click(2, 2); assert(!await modal.isVisible());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Card', exact: true }).click();
  assert(await modal.evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.screenshot({ path: `${out}/modal-mobile.png` });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Add an index', exact: true }).click();
  const newIndex = page.getByRole('button', { name: 'New index', exact: true });
  await newIndex.dblclick();
  await page.getByRole('textbox', { name: 'Index name', exact: true }).fill('My selected index');
  await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Card', exact: true }).click();
  await modal.getByRole('button', { name: 'Copy link', exact: true }).click();
  const selectedLink = await page.evaluate(() => window.__copied);
  assert(new URL(selectedLink).searchParams.getAll('i')[0].startsWith('My%20selected%20index|'));
  const metadata = await page.request.get(selectedLink, { headers: { 'user-agent': 'Twitterbot/1.0' } });
  const html = await metadata.text(); assert(html.includes('summary_large_image')); assert(html.includes('og:image'));
  assert.deepEqual(errors, []);
  await writeFile(`${out}/results.json`, JSON.stringify(images, null, 2));
  console.log('PASS: all 13 PNGs, modal, selected design link, X draft, download, Escape/backdrop/focus return, mobile.');
} finally { await browser.close(); }
