import { readFileSync } from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { gunzipSync } from "node:zlib";
import { normalizeLabel } from "../../src/data/normalize";
import { canonicalizeSnapshot } from "../../src/data/canonical-snapshot";
import type { Effort, Snapshot, Variant } from "../../src/data/types";
import { computeIndex } from "../../src/engine";
import { decodeIndex } from "../../src/lib/url";
import { resolveAAIdentity, type AAModelRecord } from "../scrape/aa-identity";
import corpus from "./fixtures/identity-cases.json";
const reproduction = JSON.parse(gunzipSync(readFileSync(path.join(__dirname, "fixtures/builder-2026-10-06.json.gz"))).toString()) as Snapshot;

interface Case {
  id: string;
  kind: string;
  record: Record<string, unknown>;
  expected: { modelId: string; effort: string; canonical: boolean };
  legacyVariantId: string;
}

function resolveCase(c: Case): string {
  if (c.kind === "aa") return resolveAAIdentity(c.record as AAModelRecord).variantId;
  const label = c.record.modelLabel as string, effort = c.record.effort as Effort;
  const n = normalizeLabel(label, effort);
  const key = c.record.sourceModelId as string;
  const modelId = n.ok ? n.modelId : `vals-model-${createHash("sha256").update(key).digest("hex").slice(0, 12)}`;
  if (c.kind === "label") return n.ok ? `${modelId}@${n.effort ?? "default"}` : "unresolved";
  const variant: Variant = { id: c.legacyVariantId, modelId, effort,
    configuration: `VALS model key: ${key}`, sourceModel: { id: key, slug: key, name: label, url: "https://www.vals.ai" } };
  return canonicalizeSnapshot({ variants: [variant], observations: [], series: [] } as unknown as Snapshot).variants[0].id;
}

/** Golden expected identities are release/effort groups, not outputs generated by this resolver. */
export function identityBenchmark(baseline = false) {
  const cases: Case[] = corpus.cases;
  const actual = cases.map(c => baseline ? c.legacyVariantId : resolveCase(c));
  const expected = cases.map(c => c.expected.canonical ? `${c.expected.modelId}@${c.expected.effort}` : c.legacyVariantId);
  const failures = cases.flatMap((c, i) => actual[i] === expected[i] ? [] : [{ case: c.id, expected: expected[i], actual: actual[i] }]);
  let trueMatches = 0, falseMerges = 0, falseSplits = 0, correctSeparations = 0;
  for (let i = 0; i < cases.length; i++) for (let j = i + 1; j < cases.length; j++) {
    const shouldMatch = expected[i] === expected[j], matched = actual[i] === actual[j];
    if (shouldMatch && matched) trueMatches++;
    else if (shouldMatch) falseSplits++;
    else if (matched) falseMerges++;
    else correctSeparations++;
  }
  const fixture = reproduction as unknown as Snapshot;
  const url = new URL(readFileSync(path.join(__dirname, "fixtures/builder-link.txt"), "utf8").trim());
  const config = decodeIndex(url.searchParams.get("i")!, "regression")!;
  const snap = baseline ? fixture : canonicalizeSnapshot(fixture);
  const result = computeIndex(snap, { ...config, variants: "all" });
  const rankingIds = result.ranked.map(r => r.variant.id);
  const expectedRankingIds = [
    ...["low", "medium", "high", "xhigh", "max"].map(e => `claude-sonnet-5.5@${e}`),
    ...["none", "low", "medium", "high", "xhigh", "max"].map(e => `gpt-5.6-luna@${e}`),
  ];
  const rankingPass = JSON.stringify([...rankingIds].sort()) === JSON.stringify([...expectedRankingIds].sort());
  return {
    cases: cases.length, passed: cases.length - failures.length, failures,
    pairs: { trueMatches, falseMerges, falseSplits, correctSeparations,
      precision: trueMatches / Math.max(1, trueMatches + falseMerges),
      recall: trueMatches / Math.max(1, trueMatches + falseSplits) },
    reproduction: { rows: rankingIds.length, expectedRows: expectedRankingIds.length, passed: rankingPass, rankingIds },
    passedAll: !failures.length && !falseMerges && !falseSplits && rankingPass,
  };
}
