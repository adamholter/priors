import assert from "node:assert/strict";
import { chromium } from "playwright";

const base = process.env.TEST_URL ?? "http://127.0.0.1:48740";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
const mix = "General%20frontier|aa-gdpval-aa:20,aa-terminalbench-v2-1:20,deepswe-1.1:20,terminalbench-4:13,arc-agi-3:13,simplebench:13|effort=strict";
try {
  await page.goto(`${base}/?${new URLSearchParams({ i: mix })}`, { waitUntil: "networkidle" });
  const footer = page.getByRole("region", { name: "Import a benchmark" });
  const controls = page.getByRole("region", { name: "Benchmarks and eligibility" });
  const bottom = async () => { const b = await footer.boundingBox(); assert(b); return b.y + b.height; };
  assert(Math.abs(await bottom() - 868) < 3, "footer should sit 32px above viewport bottom");
  const search = page.getByRole("searchbox", { name: "Add a benchmark" });
  await search.click();
  const results = page.locator('[aria-label="Available benchmarks"]');
  assert(await results.getByRole("button").count() > 10);
  await search.fill("no-such-benchmark-12345");
  await page.getByRole("status").filter({ hasText: "No matching benchmarks." }).waitFor();
  await search.fill("TERMINALBENCH 2.1");
  assert.equal(await results.getByRole("button").count(), 1);
  await search.fill("frontierswe v2");
  assert.equal(await results.getByRole("button").count(), 1);
  await search.press("Enter");
  await page.getByRole("slider", { name: /FrontierSWE.*2.*weight/i }).waitFor();
  assert.equal(await search.inputValue(), "");
  assert.equal(await results.count(), 0);
  await page.getByRole("button", { name: /^Remove FrontierSWE.*2/i }).click();
  await search.click();
  await search.fill("arc");
  await search.press("Escape");
  assert.equal(await results.count(), 0);
  await search.click();
  await controls.evaluate((el) => { el.scrollTop = el.scrollHeight; });
  assert(await controls.evaluate((el) => el.scrollTop > 0), "long sidebar must scroll");
  assert(Math.abs(await bottom() - 868) < 3, "expanded controls must not move footer");
  await page.evaluate(() => window.scrollTo(0, 500));
  assert(Math.abs(await bottom() - 868) < 3, "footer must remain pinned while document scrolls");
  await page.getByRole("button", { name: "Calculation settings", exact: true }).click();
  await page.getByRole("dialog").getByText(/Excluded variants/).waitFor();
  await page.keyboard.press("Escape");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "/tmp/priors-sidebar-desktop.png" });
  await page.setViewportSize({ width: 1100, height: 580 });
  assert(Math.abs(await bottom() - 548) < 3, "footer must fit a short desktop viewport");
  await page.waitForTimeout(300);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "short desktop must not overflow horizontally");
  await page.screenshot({ path: "/tmp/priors-sidebar-short.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.getByRole("complementary", { name: "Index controls" }).evaluate((el) => getComputedStyle(el).position === "static"));
  await page.waitForTimeout(300);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "mobile must not overflow horizontally");
  await page.screenshot({ path: "/tmp/priors-sidebar-mobile.png" });
  await page.setViewportSize({ width: 1440, height: 900 });
  const info = await page.request.get(`${base}/api/snapshot`);
  assert.equal(info.headers()["cache-control"], "no-store");
  const current = (await info.json()).snapshot;
  const before = current.generatedAt;
  if (process.env.TEST_REFRESH === "1") {
    await page.getByRole("button", { name: "Calculation settings", exact: true }).click();
    await page.getByRole("dialog").locator("summary").filter({ hasText: "Sources" }).click();
    await page.getByRole("button", { name: "Refresh sources", exact: true }).click();
    await page.getByRole("button", { name: "Scraping live sources…" }).waitFor();
    await page.getByRole("button", { name: "Refresh sources", exact: true }).waitFor({ timeout: 300_000 });
    const after = (await (await page.request.get(`${base}/api/snapshot`)).json()).snapshot;
    assert(after.generatedAt > before, "refresh button must fetch and publish new data");
    assert(after.sources.every((s) => s.status === "ok"), "all sources should succeed");
    console.log("Live refresh:", after.generatedAt, after.observations.length, "observations");
  }
  const blocked = await page.request.post(`${base}/api/snapshot`, { headers: { origin: "https://example.com", "x-priors-refresh": "1" } });
  assert.equal(blocked.status(), 403);
  const newer = { ...current, generatedAt: "2100-01-01T12:00:00.000Z", sources: [...current.sources, { sourceId: "poll-test", status: "ok", rowCount: 0, fetchedAt: "2100-01-01T12:00:00Z", unknownLabels: [] }] };
  await page.route("**/api/snapshot", (route) => route.fulfill({ json: { snapshot: newer, canRefresh: false, refreshing: false } }));
  await page.goto(`${base}/?${new URLSearchParams({ i: mix })}`, { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "Calculation settings", exact: true }).click();
  await page.getByText(/Sources · .*2100/).waitFor();
  assert(new URL(page.url()).searchParams.get("i") === mix, "new snapshots preserve the user's index");
  await page.goto(`${base}/?${new URLSearchParams({ i: mix, date: current.date })}`, { waitUntil: "networkidle" });
  await page.waitForTimeout(500);
  assert.equal(await page.getByText(/Sources · .*2100/).count(), 0, "historical snapshots must not follow latest");
  assert.equal(new URL(page.url()).searchParams.get("date"), current.date, "URL sync preserves historical date");
  assert.deepEqual(errors, []);
  console.log("Sidebar pinning, overflow, effort diagnostics, and uncached snapshot checks passed.");
} finally {
  await browser.close();
}
