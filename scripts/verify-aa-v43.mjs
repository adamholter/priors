import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { gunzipSync } from "node:zlib";
import { createRequire } from "node:module";
import { chromium } from "playwright";
import "tsx/cjs";
const require = createRequire(import.meta.url);
const { AA_V43_WEIGHTS } = require("../src/data/aa-index.ts");
const { computeIndex, selectVariants } = require("../src/engine/index.ts");
const { decodeIndices, encodeIndices } = require("../src/lib/url.ts");
const base = process.env.TEST_URL ?? "http://127.0.0.1:48740";
const snapshot = JSON.parse(gunzipSync(await readFile("data/snapshots/latest.json.gz")));
const run = snapshot.sources.find((r) => r.sourceId === "aa");
assert.equal(run.status, "ok");
assert.deepEqual(run.unknownLabels, []);
const coverage = JSON.parse(await readFile(`${run.rawPath}/coverage.json`, "utf8"));
assert.equal(coverage.tableModels, coverage.evaluationModels);
assert.equal(coverage.representedModels, coverage.mergedModels);
const aaVariants = snapshot.variants.filter((v) => v.sourceModel);
assert.equal(new Set(aaVariants.map((v) => v.sourceModel.id)).size, coverage.representedModels);
const config = { id: "aa", name: "AA v4.3", weights: AA_V43_WEIGHTS, required: [], cutoff: 0, strictness: 100, estimateMissing: false, effortMatching: "strict", variants: "all" };
const aaUrl = `${base}/?${encodeIndices([config])}`;
const result = computeIndex(snapshot, config);
assert(result.ranked.length >= 100, "the complete AA baseline must retain broad effort coverage");
const published = new Map(snapshot.observations.filter((o) => o.benchmarkId === "aa-intelligence-index-v4.3").map((o) => [o.variantId, o.value]));
const errors = result.ranked.map((r) => Math.abs(r.score - published.get(r.variant.id)));
assert(errors.every((e) => Number.isFinite(e) && e < 0.02), "reconstruction differs materially from AA");
assert(result.ranked.every((r) => r.coverage === 1 && r.values.every((v) => !v.estimated)));
const astra = result.ranked.filter((r) => r.model.id === "gpt-6-astra");
assert.deepEqual(new Set(astra.map((r) => r.variant.effort)), new Set(["none", "low", "medium", "high", "xhigh", "max"]));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const pageErrors = [];
page.on("pageerror", (e) => pageErrors.push(e.message));
try {
  await page.goto(aaUrl, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "AA v4.3", exact: true }).waitFor();
  for (const [id, weight] of Object.entries(AA_V43_WEIGHTS)) {
    const name = snapshot.benchmarks.find((b) => b.id === id).name;
    assert.equal(await page.getByRole("slider", { name: `${name} weight`, exact: true }).inputValue(), String(weight));
    assert(await page.getByRole("checkbox", { name: `${name} required`, exact: true }).isChecked());
  }
  assert.equal(await page.getByRole("slider", { name: "Strictness", exact: true }).inputValue(), "100");
  await page.getByText(`11 benchmarks · ${selectVariants(result.ranked, "best").length} models`, { exact: true }).waitFor();
  assert.equal(await page.locator("[data-k]").first().getAttribute("data-k"), result.ranked[0].variant.id);
  await page.screenshot({ path: "/tmp/priors-aa-v43/desktop.png", fullPage: true });
  await page.getByLabel("Ranking settings", { exact: true }).click();
  await page.getByRole("combobox", { name: "Ranking reasoning efforts" }).selectOption("all");
  await page.getByLabel("Ranking settings", { exact: true }).click();
  await page.getByRole("button", { name: `Show all ${result.ranked.length} variants`, exact: true }).click();
  assert.equal(await page.locator('[data-k^="gpt-6-astra@"]:visible').count(), astra.length);
  await page.getByRole("button", { name: "Calculation settings", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Calculation settings" });
  await dialog.getByRole("combobox", { name: "Inspect model calculation" }).selectOption("gpt-6-astra@max");
  await dialog.getByRole("link", { name: "GPT-6 Astra (max)", exact: true }).waitFor();
  assert.equal(await dialog.getByRole("combobox", { name: "Effort estimates" }).inputValue(), "strict");
  await dialog.screenshot({ path: "/tmp/priors-aa-v43/calculation.png" });
  await page.keyboard.press("Escape");
  const weight = page.getByRole("slider", { name: "AA-Briefcase weight", exact: true });
  await weight.fill("20");
  await page.waitForTimeout(300);
  assert.equal(decodeIndices(new URL(page.url()).searchParams)[0].weights["aa-briefcase"], 20);
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await weight.inputValue(), "20");
  const share = await page.request.get(`${base}/og${new URL(page.url()).search}`);
  assert.equal(share.status(), 200);
  assert.match(share.headers()["content-type"], /image/);
  await page.goto(aaUrl, { waitUntil: "networkidle" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: "/tmp/priors-aa-v43/mobile.png", fullPage: true });
  // A pre-existing anonymous custom index remains authoritative.
  await page.goto(`${base}/?i=${encodeURIComponent("My mix|deepswe-1.1:75,simplebench:25")}`, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "My mix", exact: true }).waitFor();
  assert.equal(await page.getByRole("slider", { name: /weight$/ }).count(), 2);
  assert.deepEqual(pageErrors, []);
  const report = { date: snapshot.date, aaCatalogConfigurations: aaVariants.length, evaluationPages: coverage.discoveredPages, baselineConfigurations: result.ranked.length, baselineModels: selectVariants(result.ranked, "best").length, maxAbsoluteScoreDifference: Math.max(...errors), meanAbsoluteScoreDifference: errors.reduce((a, b) => a + b, 0) / errors.length, astraEfforts: astra.map((r) => r.variant.effort), browserChecks: "explicit AA weights, exact effort, full catalog, rankings, calculations, sliders, URL reload, share card, mobile, existing custom URL", consoleErrors: pageErrors };
  await writeFile("/tmp/priors-aa-v43/verification.json", JSON.stringify(report, null, 2));
  console.log(report);
} finally { await browser.close(); }
