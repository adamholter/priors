  assert.deepEqual(errors, []);
  console.log("PASS: outside click, Escape, focus dismissal/return, exclusive popovers, selection dismissal, search, modal scroll lock, keyboard selection/rename/cancel/blur, immediate sharing, clipboard error recovery, mobile.");
