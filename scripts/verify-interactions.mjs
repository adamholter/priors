  await page.mouse.click(5, 5); assert(!await dialog.isVisible());
  assert(await calculations.evaluate((el) => el === document.activeElement));
  await page.waitForFunction(() => document.body.style.overflow !== "hidden");
  await calculations.click(); await page.keyboard.press("Escape"); assert(!await dialog.isVisible());
  await page.getByRole("button", { name: "Add an index", exact: true }).click();
  const newer = page.getByRole("button", { name: "New index", exact: true });
  await newer.focus(); await page.keyboard.press("F2");
  const name = page.getByRole("textbox", { name: "Index name", exact: true });
  await name.fill("Discard this"); await page.keyboard.press("Escape"); assert(await newer.isVisible());
  await newer.focus(); await page.keyboard.press("F2"); await name.fill("My research"); await page.keyboard.press("Enter");
  const renamed = page.getByRole("button", { name: "My research", exact: true }); assert(await renamed.isVisible());
  assert(await renamed.evaluate((el) => el === document.activeElement));
  const original = page.getByRole("button", { name: "AA v4.3", exact: true });
  await original.focus(); await page.keyboard.press("Space"); assert.equal(await original.getAttribute("aria-pressed"), "true");
  await renamed.focus(); await page.keyboard.press("Enter"); assert.equal(await renamed.getAttribute("aria-pressed"), "true");
  await renamed.dblclick(); await name.fill("Saved by blur"); await page.getByRole("heading", { name: "Your mix", exact: true }).click();
  assert(await page.getByRole("button", { name: "Saved by blur", exact: true }).isVisible());

  await page.getByRole("slider", { name: "AA-Briefcase weight", exact: true }).fill("27");
  await page.getByRole("button", { name: /Copy link|Link copied/ }).click();
  const copied = await page.evaluate(() => window.__copied.at(-1));
  assert(new URL(copied).searchParams.getAll("i").some((i) => i.includes("aa-briefcase:27")));
  const card = page.getByRole("button", { name: "Card", exact: true }); await card.click();
  const share = page.getByRole("dialog", { name: "Share card", exact: true });
  assert((await share.getByRole("link", { name: "Download" }).getAttribute("href")).includes("aa-briefcase%3A27"));
