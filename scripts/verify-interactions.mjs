  await page.getByRole("button", { name: /Copy link|Link copied/ }).click();
  await page.getByRole("alert").getByText(/Copy failed/).waitFor();
  await page.evaluate(() => { window.__clipboardFail = false; });
  await page.getByRole("button", { name: /Copy link|Link copied/ }).click();
  await page.getByRole("alert").filter({ hasText: "Could not copy" }).waitFor({ state: "hidden" });
  await page.screenshot({ path: "/tmp/priors-interactions-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await calculations.click();
  assert(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), "dialog fits mobile");
  await page.screenshot({ path: "/tmp/priors-interactions-mobile.png" });
  await page.mouse.click(2, 2); assert(!await dialog.isVisible());
