  await search.click(); await page.keyboard.press("Escape"); assert(!await options.isVisible());
  await search.fill("SimpleBench"); await options.getByRole("button", { name: /SimpleBench/ }).click();
  assert(!await options.isVisible()); assert(await search.evaluate((el) => el === document.activeElement));

  const calculations = page.getByRole("button", { name: "Calculation settings", exact: true });
  const dialog = page.getByRole("dialog", { name: "Calculation settings" });
  await calculations.click(); assert(await dialog.isVisible());
